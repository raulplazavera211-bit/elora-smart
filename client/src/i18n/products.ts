export const PRODUCTS_LOCALE: Record<string, ProductsLocaleMap> = { es, en, pt, fr, it };

/**
 * Devuelve los datos localizados de un producto según el idioma activo.
 * Si no existe traducción, cae en español.
 */
export function getProductLocale(productId: string, lang: string): ProductLocale | undefined {
  const map = PRODUCTS_LOCALE[lang] ?? PRODUCTS_LOCALE['es'];
  return map[productId] ?? PRODUCTS_LOCALE['es'][productId];
}
